package com.mycompany.password_manager;

import java.io.File;
import java.io.IOException;
import java.nio.file.Files;
import java.security.SecureRandom;
import java.util.Base64;
import javax.crypto.Cipher;
import javax.crypto.spec.IvParameterSpec;
import javax.crypto.spec.SecretKeySpec;

/**
 *
 * @author ABC
 */
public class AESEncryption {
    
    // key generation
    // it checks if key is already existing first
    // if key is already existing, use the key
    // otherwise, generate new key
    private static byte[] keyGeneration() {

        File keyTxtFile = new File("key.txt");
        
        if(!keyTxtFile.exists()) {
            // create a 16 bytes array
            byte[] newKey = new byte[16];
            
            // put randomly generated bytes into newKey
            new SecureRandom().nextBytes(newKey);
            
            try {
                // save key into key.txt file.
                // keyTxtFile.toPath() : the location of key.txt file.
                Files.write(keyTxtFile.toPath(), newKey);
            }
            catch(IOException e) {
                System.out.println("Error from key generation.\n");
                return null;
            }
            
            return newKey;
        }
        
        try {
            // read the txt file and return it.
            return Files.readAllBytes(keyTxtFile.toPath());
        }
        catch(IOException e) {
            System.out.println("Error from key reading");
            return null;
        }
    }
    
    
    public static String encrypt(String plainPW) {
        
        // get key
        byte[] key = new byte[16];
        key = keyGeneration();
        
        // generate IV (randomly generated bytes)
        byte[] iv = new byte[16];
        new SecureRandom().nextBytes(iv);
        
        // convert the key into form for AES encryption
        SecretKeySpec keySpec = new SecretKeySpec(key, "AES");
        
        // convert the iv into form for AES encryption
        IvParameterSpec ivSpec = new IvParameterSpec(iv);
        
        try {
            
            // make cipher to encrypt the password
            // this of cipher as an encryptiong/decrypting tool
            // and it has lots of options other than AES
            // so we should specify encryption type, which is AES for this app
            Cipher cipher = Cipher.getInstance("AES/CBC/PKCS5Padding");
            
            // specify encryption, key, and IV
            cipher.init(Cipher.ENCRYPT_MODE, keySpec, ivSpec);
            
            // plainPW.getBytes("UTF-8") : convert string into byte
            // cipher.doFinal : start encrypting
            // now we have encrypted version of password in variable "encrypted"
            byte[] encrypted = cipher.doFinal(plainPW.getBytes("UTF-8"));
            
            // Encode iv into base64 string
            String ivBase64 = Base64.getEncoder().encodeToString(iv);
            
            // encode encrypted into base64 string
            String encryptedBase64 = Base64.getEncoder().encodeToString(encrypted);
            
            // put iv and encrypted password together to decrypt later
            // if iv is ommitted, it can't be decrypted
            String fianlEncryptedVersion = ivBase64 + ":" + encryptedBase64;
            
            return fianlEncryptedVersion;
        }
        catch (Exception e) {
            System.out.println("Encryption error");
            return null;
        }
    }
    
    public static String decrypt(String encryptedPW) {
        
        // get key
        byte[] key = new byte[16];
        key = keyGeneration();
        
        // get encrypted password(iv + encrypted password) and spearte them into iv and encrypted password
        // also do base64 decode and store them as byte[]
        String[] parts = encryptedPW.split(":");
        byte[] iv = Base64.getDecoder().decode(parts[0]);
        byte[] encrypted = Base64.getDecoder().decode(parts[1]);
        
        // convert the key into form for AES encryption
        SecretKeySpec keySpec = new SecretKeySpec(key, "AES");
        
        // convert the iv into form for AES encryption
        IvParameterSpec ivSpec = new IvParameterSpec(iv);
        
        try {
            // decryption
            Cipher cipher = Cipher.getInstance("AES/CBC/PKCS5Padding");
            cipher.init(Cipher.DECRYPT_MODE, keySpec, ivSpec);
            byte[] decrypted = cipher.doFinal(encrypted);
            
            // convert decrypted into string
            String finalDecrypted = new String(decrypted, "UTF-8");
            
            return finalDecrypted;
        }
        catch(Exception e) {
            System.out.println("Error from decryption");
            return null;
        }
    }
}
