    private void RemoveBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_RemoveBtnActionPerformed
        // TODO add your handling code here:
        String service = serviceTf.getText().trim().toLowerCase();
        String ID = idTf.getText().trim();

        ArrayList<String> accounts = new ArrayList<>();

        boolean found = false;

        try {
            Scanner scan = new Scanner(new File("Holder.txt"));

            while (scan.hasNextLine()) {

                String line = scan.nextLine();

                String[] details = line.split("\\s*\\|\\s*", 4);

                if (details.length >= 4
                        && details[0].equalsIgnoreCase(service)
                        && details[1].equals(ID)) {

                    found = true;

                } else {

                    accounts.add(line);

                }
            }

            scan.close();

            if (found) {

                PrintWriter writer = new PrintWriter("Holder.txt");

                for (String account : accounts) {
                    writer.println(account);
                }

                writer.close();

                outputTa.setText("Account successfully deleted.");

            } else {

                outputTa.setText("Account not found.");

            }

        } catch (FileNotFoundException e) {

            outputTa.setText("Error: " + e.getMessage());

        }

    }//GEN-LAST:event_RemoveBtnActionPerformed

